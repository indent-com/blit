function upsertRecords(path: string, content: string): Uint8Array {
  const bytes = new TextEncoder().encode(content);
  const buf: number[] = [];
  appendFsRecord(buf, {
    kind: "upsert",
    path,
    entryFlags: FS_ENTRY_FILE,
    size: bytes.length,
    mtimeNs: 42n,
    mode: 0o644,
    hash: 7n,
    content: { kind: "full", data: bytes },
  });
  return new Uint8Array(buf);
}

function upsertWithHash(
  path: string,
  content: string,
  hash: bigint,
): Uint8Array {
  const bytes = new TextEncoder().encode(content);
  const buf: number[] = [];
  appendFsRecord(buf, {
    kind: "upsert",
    path,
    entryFlags: FS_ENTRY_FILE,
    size: bytes.length,
    mtimeNs: 1n,
    mode: 0o644,
    hash,
    content: { kind: "full", data: bytes },
  });
  return new Uint8Array(buf);
}

function concat(...parts: Uint8Array[]): Uint8Array {
  const out = new Uint8Array(parts.reduce((n, p) => n + p.length, 0));
  let offset = 0;
  for (const p of parts) {
    out.set(p, offset);
    offset += p.length;
  }
  return out;
}

