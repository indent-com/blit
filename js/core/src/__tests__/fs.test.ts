describe("FsMirror.apply", () => {
  it("reports liveChanged only when live actually mutates", () => {
    const mirror = new FsMirror();
    // RESET: records go to staging, live untouched.
    let r = mirror.apply(
      buildFsUpdateMessage(1, 1, FS_UPDATE_RESET, upsertRecords("a", "x")),
    )!;
    expect(r.liveChanged).toBe(false);
    expect(mirror.staged?.size).toBe(1);
    expect(mirror.live.size).toBe(0);
    // More staged records: still unchanged.
    r = mirror.apply(buildFsUpdateMessage(1, 2, 0, upsertRecords("b", "y")))!;
    expect(r.liveChanged).toBe(false);
    // The SYNC swap changes live.
    r = mirror.apply(
      buildFsUpdateMessage(1, 3, FS_UPDATE_SYNC, new Uint8Array(0)),
    )!;
    expect(r.liveChanged).toBe(true);
    expect(mirror.staged).toBeNull();
    expect(mirror.live.size).toBe(2);
    // Direct applies change live.
    r = mirror.apply(buildFsUpdateMessage(1, 4, 0, upsertRecords("c", "z")))!;
    expect(r.liveChanged).toBe(true);
    // An empty direct update changes nothing.
    r = mirror.apply(buildFsUpdateMessage(1, 5, 0, new Uint8Array(0)))!;
    expect(r.liveChanged).toBe(false);
    // Deleting a path that is not mirrored changes nothing.
    const buf: number[] = [];
    appendFsRecord(buf, { kind: "delete", path: "missing" });
    r = mirror.apply(buildFsUpdateMessage(1, 6, 0, new Uint8Array(buf)))!;
    expect(r.liveChanged).toBe(false);
    // Deleting a mirrored path does.
    const del: number[] = [];
    appendFsRecord(del, { kind: "delete", path: "c" });
    r = mirror.apply(buildFsUpdateMessage(1, 7, 0, new Uint8Array(del)))!;
    expect(r.liveChanged).toBe(true);
  });

  it("collects decoded records for the caller in one pass", () => {
    const mirror = new FsMirror();
    const collected: FsRecord[] = [];
    mirror.apply(
      buildFsUpdateMessage(
        1,
        1,
        FS_UPDATE_RESET | FS_UPDATE_SYNC,
        concat(upsertRecords("a", "x"), upsertRecords("b", "y")),
      ),
      collected,
    );
    expect(
      collected.map((r) => (r.kind === "upsert" ? r.path : r.kind)),
    ).toEqual(["a", "b"]);
  });
});

describe("fs LZ4 helpers", () => {
  it("literal-only compression round-trips", () => {
    for (const len of [0, 1, 14, 15, 16, 100, 300, 5000]) {
      const data = new Uint8Array(len);
      for (let i = 0; i < len; i++) data[i] = i & 0xff;
      const out = fsDecompress(fsCompressLiteral(data));
      expect(out).not.toBeNull();
      expect(toHex(out!)).toBe(toHex(data));
    }
  });

  it("encodes empty content as lz4_flex does (size prefix + 0x00 token)", () => {
    // A bare 4-byte size prefix is NOT a valid empty block: lz4_flex
    // rejects it (ExpectedAnotherByte) and the server drops the whole
    // message — an empty-file FS_WRITE or an LSP_BUFFER release would
    // vanish silently.
    expect(toHex(fsCompressLiteral(new Uint8Array()))).toBe("0000000000");
  });

  it("decoder block-copies disjoint matches and byte-copies overlaps", () => {
    // "abcdefgh" + match(offset 8, len 8) → the disjoint copyWithin path.
    const disjoint = new Uint8Array([
      16, 0, 0, 0, 0x84, 97, 98, 99, 100, 101, 102, 103, 104, 8, 0,
    ]);
    expect(new TextDecoder().decode(fsDecompress(disjoint)!)).toBe(
      "abcdefghabcdefgh",
    );
    // "ab" + match(offset 2, len 14) → the overlapping byte-copy path.
    const overlap = new Uint8Array([16, 0, 0, 0, 0x2a, 97, 98, 2, 0]);
    expect(new TextDecoder().decode(fsDecompress(overlap)!)).toBe(
      "abababababababab",
    );
  });

  it("applyFsDelta handles multi-byte LEB128 and rejects junk", () => {
    const base = new Uint8Array(300);
    for (let i = 0; i < 300; i++) base[i] = i & 0xff;
    // COPY(offset=200 → 0xC8 0x01, len=100)
    const ops = new Uint8Array([0x01, 0xc8, 0x01, 100]);
    const out = applyFsDelta(base, ops)!;
    expect(toHex(out)).toBe(toHex(base.subarray(200, 300)));
    // COPY out of range.
    expect(
      applyFsDelta(base, new Uint8Array([0x01, 0xc8, 0x02, 100])),
    ).toBeNull();
    // Unknown op.
    expect(applyFsDelta(base, new Uint8Array([0x03]))).toBeNull();
    // Truncated INSERT.
    expect(applyFsDelta(base, new Uint8Array([0x02, 9, 1]))).toBeNull();
  });
});

/**
 * Decode one framed LZ4 payload while asserting the standard block end
 * rules that lz4_flex and the reference decoder assume: the last sequence
 * is literal-only, matches never start within the last 12 bytes, and the
 * last 5 bytes are literals.
 */
function decodeAssertingBlockRules(payload: Uint8Array): Uint8Array {
  const v = new DataView(
    payload.buffer,
    payload.byteOffset,
    payload.byteLength,
  );
  const outLen = v.getUint32(0, true);
  const src = payload.subarray(4);
  const out = new Uint8Array(outLen);
  let si = 0;
  let di = 0;
  if (outLen === 0) {
    expect(src.length).toBeLessThanOrEqual(1);
    return out;
  }
  while (si < src.length) {
    const token = src[si++];
    let litLen = token >> 4;
    if (litLen === 15) {
      let b: number;
      do {
        b = src[si++];
        litLen += b;
      } while (b === 255);
    }
    out.set(src.subarray(si, si + litLen), di);
    si += litLen;
    di += litLen;
    if (si >= src.length) break; // final sequence: literals only
    expect(di).toBeLessThanOrEqual(outLen - 12); // match start rule
    const offset = src[si] | (src[si + 1] << 8);
    si += 2;
    expect(offset).toBeGreaterThan(0);
    expect(offset).toBeLessThanOrEqual(di);
    let matchLen = (token & 0x0f) + 4;
    if ((token & 0x0f) === 15) {
      let b: number;
      do {
        b = src[si++];
        matchLen += b;
      } while (b === 255);
    }
    expect(di + matchLen).toBeLessThanOrEqual(outLen - 5); // trailing literals rule
    let mi = di - offset;
    for (let i = 0; i < matchLen; i++) out[di++] = out[mi++];
  }
  expect(di).toBe(outLen);
  return out;
}

/** Deterministic byte stream (xorshift32) for incompressible fixtures. */
function randomBytes(len: number, seed = 0x9e3779b9): Uint8Array {
  const out = new Uint8Array(len);
  let s = seed >>> 0;
  for (let i = 0; i < len; i++) {
    s ^= s << 13;
    s >>>= 0;
    s ^= s >>> 17;
    s ^= s << 5;
    s >>>= 0;
    out[i] = s & 0xff;
  }
  return out;
}

describe("fsCompress (real LZ4 block encoder)", () => {
  const enc = (s: string) => new TextEncoder().encode(s);
  const cases: Array<[string, Uint8Array]> = [
    ["empty", new Uint8Array(0)],
    ["tiny", enc("hello!")],
    ["twelve bytes (below the match floor)", enc("abcabcabcabc")],
    ["thirteen bytes", enc("abcabcabcabca")],
    ["ends deep in a match", concat(enc("prefix-"), new Uint8Array(200))],
    [
      "single-byte run (overlapping match + length extension)",
      new Uint8Array(1000).fill(0x61),
    ],
    ["repetitive", enc("abcd".repeat(4096))],
    [
      "long literal head then matches",
      concat(randomBytes(300), enc("xyzw".repeat(128))),
    ],
    ["incompressible random", randomBytes(8192)],
    [
      "text-like",
      enc("All work and no play makes blit a dull tool. ".repeat(64)),
    ],
  ];

  it("round-trips through the production decoder", () => {
    for (const [name, data] of cases) {
      const out = fsDecompress(fsCompress(data));
      expect(out, name).not.toBeNull();
      expect(toHex(out!), name).toBe(toHex(data));
    }
  });

  it("emits standard blocks honoring the end-of-block rules", () => {
    for (const [name, data] of cases) {
      expect(toHex(decodeAssertingBlockRules(fsCompress(data))), name).toBe(
        toHex(data),
      );
    }
  });

  it("actually compresses repetitive input", () => {
    const data = enc("abcd".repeat(4096));
    expect(fsCompress(data).length).toBeLessThan(data.length / 8);
    const run = new Uint8Array(1000).fill(0x61);
    expect(fsCompress(run).length).toBeLessThan(32);
  });

  it("never exceeds the literal-only encoding", () => {
    for (const [name, data] of cases) {
      expect(fsCompress(data).length, name).toBeLessThanOrEqual(
        fsCompressLiteral(data).length,
      );
    }
  });

  it("falls back to the literal-only block for tiny inputs", () => {
    for (const len of [0, 1, 5, 12]) {
      expect(toHex(fsCompress(randomBytes(len)))).toBe(
        toHex(fsCompressLiteral(randomBytes(len))),
      );
    }
  });

  it("round-trips every length across the block-rule thresholds", () => {
    for (let len = 0; len <= 80; len++) {
      // Half-repetitive so lengths just over 13 can produce matches whose
      // end collides with the trailing-literals rule.
      const data = new Uint8Array(len);
      for (let i = 0; i < len; i++) data[i] = i < len / 2 ? i & 0xff : 0x61;
      const out = decodeAssertingBlockRules(fsCompress(data));
      expect(toHex(out), `len ${len}`).toBe(toHex(data));
    }
  });
});

