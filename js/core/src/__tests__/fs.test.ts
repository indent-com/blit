describe("BlitConnection writes", () => {
  async function writeReadyHandle() {
    const transport = new MockTransport();
    const conn = new BlitConnection({
      id: "test",
      transport,
      wasm,
      autoConnect: false,
    });
    transport.pushHello(1, FEATURE_FS);
    transport.pushReady();
    const handlePromise = conn.syncFs("/w");
    const syncMsg = transport.sent.find((m) => m[0] === C2S_FS_SYNC)!;
    pushSynced(transport, syncMsg[1] | (syncMsg[2] << 8), 7, 0, "/w");
    const handle = await handlePromise;
    await flushTimers();
    return { conn, transport, handle };
  }

  it("writeFile resolves with the hash and records lastWrittenHash", async () => {
    const { conn, transport, handle } = await writeReadyHandle();
    const p = handle.writeFile("a.txt", new TextEncoder().encode("hi"), {
      create: true,
    });
    const writeMsg = transport.sent.find((m) => m[0] === C2S_FS_WRITE)!;
    expect(writeMsg).toBeDefined();
    const nonce = writeMsg[1] | (writeMsg[2] << 8);
    transport.push(buildFsDoneMessage(nonce, FS_DONE_OK, 0xabcdn, 123n));
    const res = await p;
    expect(res.hash).toBe(0xabcdn);
    expect(res.mtimeNs).toBe(123n);
    // Recorded for self-echo suppression.
    expect(handle.lastWrittenHash("a.txt")).toBe(0xabcdn);
    conn.dispose();
  });

  it("writeFile rejects with FsConflictError carrying the disk hash", async () => {
    const { conn, transport, handle } = await writeReadyHandle();
    const p = handle.writeFile("a.txt", new Uint8Array(), { ifHash: 1n });
    const writeMsg = transport.sent.find((m) => m[0] === C2S_FS_WRITE)!;
    const nonce = writeMsg[1] | (writeMsg[2] << 8);
    transport.push(buildFsDoneMessage(nonce, FS_DONE_CONFLICT, 0x999n, 0n));
    await expect(p).rejects.toMatchObject({
      name: "FsConflictError",
      hash: 0x999n,
    });
    // A conflict must not record a lastWrittenHash.
    expect(handle.lastWrittenHash("a.txt")).toBeUndefined();
    conn.dispose();
  });

  it("mkdir/remove/rename emit FS_OP with the right selector and flags", async () => {
    const { conn, transport, handle } = await writeReadyHandle();
    // Fire-and-forget: no FS_DONE is mocked, so these stay pending and are
    // rejected by dispose() below — handle the rejection so it isn't unhandled.
    const pending = [
      handle.mkdir("d", { createParents: true, mode: 0o700 }),
      handle.remove("d"),
      handle.rename("d", "e"),
    ];
    pending.forEach((p) => void p.catch(() => {}));
    const ops = transport.sent.filter((m) => m[0] === C2S_FS_OP);
    expect(ops.map((m) => m[5])).toEqual([
      FS_OP_MKDIR,
      FS_OP_REMOVE,
      FS_OP_RENAME,
    ]);
    // mkdir carried MKPARENTS in its flags byte.
    expect(ops[0][6] & FS_OP_MKPARENTS).toBe(FS_OP_MKPARENTS);
    conn.dispose();
  });

  it("symlink/hardlink emit FS_OP and record the returned hash", async () => {
    const { conn, transport, handle } = await writeReadyHandle();
    const p = handle.symlink("../elsewhere/t", "ln");
    const q = handle.hardlink("src.txt", "ln2", { force: true });
    void q.catch(() => {});
    const ops = transport.sent.filter((m) => m[0] === C2S_FS_OP);
    expect(ops.map((m) => m[5])).toEqual([FS_OP_SYMLINK, FS_OP_HARDLINK]);
    // Default is create-exclusive (no NO_CAS); force sets it.
    expect(ops[0][6] & FS_OP_NO_CAS).toBe(0);
    expect(ops[1][6] & FS_OP_NO_CAS).toBe(FS_OP_NO_CAS);
    const nonce = ops[0][1] | (ops[0][2] << 8);
    transport.push(buildFsDoneMessage(nonce, FS_DONE_OK, 0x77n, 1n));
    await p;
    // Recorded for self-echo suppression, keyed by the link path.
    expect(handle.lastWrittenHash("ln")).toBe(0x77n);
    conn.dispose();
  });

  it("drops the lastWritten entry once its echo upsert is observed", async () => {
    const { conn, transport } = fsReadyConnection();
    const during: Array<bigint | undefined> = [];
    let handle: FsSyncHandle | undefined;
    const handlePromise = conn.syncFs("/w", {
      content: true,
      onRecord: () => during.push(handle?.lastWrittenHash("a.txt")),
    });
    const syncMsg = transport.sent.find((m) => m[0] === C2S_FS_SYNC)!;
    pushSynced(transport, syncMsg[1] | (syncMsg[2] << 8), 7, 0, "/w");
    handle = await handlePromise;
    await flushTimers();

    const writePromise = handle.writeFile(
      "a.txt",
      new TextEncoder().encode("hi"),
    );
    const writeMsg = transport.sent.find((m) => m[0] === C2S_FS_WRITE)!;
    const nonce = writeMsg[1] | (writeMsg[2] << 8);
    transport.push(buildFsDoneMessage(nonce, FS_DONE_OK, 0xabcdn, 1n));
    await writePromise;
    expect(handle.lastWrittenHash("a.txt")).toBe(0xabcdn);

    // A non-matching upsert keeps the entry — the echo is still coming.
    transport.push(
      buildFsUpdateMessage(7, 1, 0, upsertWithHash("a.txt", "other", 0x1n)),
    );
    expect(handle.lastWrittenHash("a.txt")).toBe(0xabcdn);

    // The echo: still visible inside callbacks, consumed afterwards.
    transport.push(
      buildFsUpdateMessage(7, 2, 0, upsertWithHash("a.txt", "hi", 0xabcdn)),
    );
    expect(during[during.length - 1]).toBe(0xabcdn);
    expect(handle.lastWrittenHash("a.txt")).toBeUndefined();
    conn.dispose();
  });

  it("scopes lastWritten to the writing handle, not the shared sync", async () => {
    const { conn, transport } = fsReadyConnection();
    const writerPromise = conn.syncFs("/w", { content: true });
    const syncMsg = transport.sent.find((m) => m[0] === C2S_FS_SYNC)!;
    pushSynced(transport, syncMsg[1] | (syncMsg[2] << 8), 7, 0, "/w");
    const writer = await writerPromise;
    await flushTimers();

    // Wire-identical second open: joins the same share, no second sync.
    const seen: Array<{ hash: bigint; suppressed: boolean }> = [];
    let reader: FsSyncHandle | undefined;
    const readerPromise = conn.syncFs("/w", {
      content: true,
      onRecord: (r) => {
        if (r.kind === "upsert")
          seen.push({
            hash: r.hash,
            suppressed: reader?.lastWrittenHash(r.path) === r.hash,
          });
      },
    });
    reader = await readerPromise;
    await flushTimers();
    expect(transport.sent.filter((m) => m[0] === C2S_FS_SYNC)).toHaveLength(1);

    const writePromise = writer.writeFile(
      "a.txt",
      new TextEncoder().encode("hi"),
    );
    const writeMsg = transport.sent.find((m) => m[0] === C2S_FS_WRITE)!;
    const nonce = writeMsg[1] | (writeMsg[2] << 8);
    transport.push(buildFsDoneMessage(nonce, FS_DONE_OK, 0xabcdn, 1n));
    await writePromise;

    // Recorded on the writing handle only: to the other consumer this
    // write is an external change, and its editor must reload on the echo.
    expect(writer.lastWrittenHash("a.txt")).toBe(0xabcdn);
    expect(reader.lastWrittenHash("a.txt")).toBeUndefined();

    transport.push(
      buildFsUpdateMessage(7, 1, 0, upsertWithHash("a.txt", "hi", 0xabcdn)),
    );
    expect(seen).toEqual([{ hash: 0xabcdn, suppressed: false }]);
    // Consumed from the writer's map once the echo has been delivered.
    expect(writer.lastWrittenHash("a.txt")).toBeUndefined();
    conn.dispose();
  });

  it("surfaces a read-only server's PERMISSION refusal", async () => {
    // Writes share FEATURE_FS; a BLIT_FS_WRITE=0 server answers each
    // write with FS_DONE PERMISSION instead of withholding a bit.
    const { conn, transport, handle } = await writeReadyHandle();
    const p = handle.writeFile("a", new Uint8Array());
    const writeMsg = transport.sent.find((m) => m[0] === C2S_FS_WRITE)!;
    const nonce = writeMsg[1] | (writeMsg[2] << 8);
    transport.push(buildFsDoneMessage(nonce, FS_DONE_PERMISSION, 0n, 0n));
    await expect(p).rejects.toThrow(/permission denied/);
    conn.dispose();
  });
});

