/** Hand-build an S2C_FS_INDEX (literal-only LZ4, which real decoders accept). */
function buildIndexResult(
  nonce: number,
  status: number,
  flags: number,
  paths: string[],
): Uint8Array {
  const enc = new TextEncoder();
  const raws = paths.map((p) => enc.encode(p));
  const raw = new Uint8Array(raws.reduce((n, b) => n + 2 + b.length, 0));
  const rv = new DataView(raw.buffer);
  let off = 0;
  for (const b of raws) {
    rv.setUint16(off, b.length, true);
    raw.set(b, off + 2);
    off += 2 + b.length;
  }
  const payload = fsCompressLiteral(raw);
  const msg = new Uint8Array(9 + payload.length);
  const v = new DataView(msg.buffer);
  msg[0] = S2C_FS_INDEX;
  v.setUint16(1, nonce, true);
  msg[3] = status;
  msg[4] = flags;
  v.setUint32(5, paths.length, true);
  msg.set(payload, 9);
  return msg;
}

describe("fs index codec", () => {
  it("C2S builder emits the bytes pinned in Rust", () => {
    // Matches `fs_index_request_roundtrip` in crates/remote/src/fs.rs.
    expect(toHex(buildFsIndexMessage(0x0102, "/tmp/watch me"))).toBe(
      "470201000d002f746d702f7761746368206d65",
    );
  });

  it("result parse: roundtrip, empty list, count mismatch", () => {
    const paths = ["a.txt", "sub/b.txt", ""];
    const msg = buildIndexResult(7, FS_DONE_OK, FS_INDEX_TRUNCATED, paths);
    expect(parseFsIndexResult(msg)).toEqual({
      nonce: 7,
      status: FS_DONE_OK,
      flags: FS_INDEX_TRUNCATED,
      paths,
    });
    expect(
      parseFsIndexResult(buildIndexResult(8, FS_DONE_NOT_FOUND, 0, [])),
    ).toEqual({
      nonce: 8,
      status: FS_DONE_NOT_FOUND,
      flags: 0,
      paths: [],
    });
    const lying = buildIndexResult(9, FS_DONE_OK, 0, ["a"]);
    new DataView(lying.buffer).setUint32(5, 2, true);
    expect(parseFsIndexResult(lying)).toBeNull();
    // A count over the protocol cap is malformed before any decoding.
    const over = buildIndexResult(10, FS_DONE_OK, 0, []);
    new DataView(over.buffer).setUint32(5, FS_INDEX_MAX_COUNT + 1, true);
    expect(parseFsIndexResult(over)).toBeNull();
  });
});

