// -- FS_GREP (docs/design/fs-grep.md) ---------------------------------------

/** Frame one record the way the Rust `append_fs_grep_record` does. */
function grepRecord(kind: number, body: number[]): number[] {
  const len = 1 + body.length;
  return [
    len & 0xff,
    (len >> 8) & 0xff,
    (len >> 16) & 0xff,
    (len >> 24) & 0xff,
    kind,
    ...body,
  ];
}
const u16le = (n: number) => [n & 0xff, (n >> 8) & 0xff];
const u32le = (n: number) => [
  n & 0xff,
  (n >> 8) & 0xff,
  (n >> 16) & 0xff,
  (n >> 24) & 0xff,
];
const strBytes = (s: string) => [...new TextEncoder().encode(s)];

function fileRecord(flags: number, n: number, path: string): number[] {
  const pb = strBytes(path);
  return grepRecord(FS_GREP_RECORD_FILE, [
    flags,
    ...u16le(n),
    ...u16le(pb.length),
    ...pb,
  ]);
}
function matchRecord(
  line: number,
  col: number,
  endCol: number,
  text: string,
  endLine = line,
): number[] {
  const tb = strBytes(text);
  return grepRecord(FS_GREP_RECORD_MATCH, [
    ...u32le(line),
    ...u32le(col),
    ...u32le(endLine),
    ...u32le(endCol),
    ...u32le(tb.length),
    ...tb,
  ]);
}

/** Hand-build an S2C_FS_GREP, literal-only LZ4 as real decoders accept. */
function buildGrepResult(
  nonce: number,
  status: number,
  flags: number,
  detail: string,
  records: number[],
): Uint8Array {
  const db = new TextEncoder().encode(detail);
  const payload = fsCompressLiteral(new Uint8Array(records));
  const msg = new Uint8Array(7 + db.length + payload.length);
  const v = new DataView(msg.buffer);
  msg[0] = S2C_FS_GREP;
  v.setUint16(1, nonce, true);
  msg[3] = status;
  msg[4] = flags;
  v.setUint16(5, db.length, true);
  msg.set(db, 7);
  msg.set(payload, 7 + db.length);
  return msg;
}

describe("fs grep codec", () => {
  it("C2S builder emits the bytes pinned in Rust", () => {
    // Matches `fs_grep_request_roundtrip` in crates/remote/src/fs.rs.
    expect(
      toHex(
        buildFsGrepMessage(0x0102, "/tmp/root", "fn \\w+", {
          caseSensitive: true,
          regex: true,
          maxMatches: 500,
          maxPerFile: 50,
        }),
      ),
    ).toBe("48020103f401320009002f746d702f726f6f740600666e205c772b");
  });

  it("defaults to case-insensitive literal with server-default budgets", () => {
    const m = buildFsGrepMessage(1, "/r", "q");
    expect(m[3]).toBe(0);
    const v = new DataView(m.buffer);
    expect(v.getUint16(4, true)).toBe(0);
    expect(v.getUint16(6, true)).toBe(0);
    expect(buildFsGrepMessage(1, "/r", "q", { caseSensitive: true })[3]).toBe(
      FS_GREP_CASE_SENSITIVE,
    );
    expect(buildFsGrepMessage(1, "/r", "q", { regex: true })[3]).toBe(
      FS_GREP_REGEX,
    );
  });

  it("groups matches under their file and flags ignored ones", () => {
    const records = [
      ...fileRecord(0, 2, "src/main.rs"),
      ...matchRecord(41, 4, 6, "    fn main() {"),
      ...matchRecord(99, 0, 2, "fn helper()"),
      ...fileRecord(FS_GREP_FILE_IGNORED, 1, "target/debug/build.rs"),
      ...matchRecord(0, 0, 2, ""),
    ];
    const parsed = parseFsGrepResult(
      buildGrepResult(7, FS_DONE_OK, FS_GREP_TRUNCATED, "", records),
    );
    expect(parsed).toEqual({
      nonce: 7,
      status: FS_DONE_OK,
      flags: FS_GREP_TRUNCATED,
      detail: "",
      files: [
        {
          path: "src/main.rs",
          ignored: false,
          matches: [
            {
              line: 41,
              col: 4,
              endLine: 41,
              endCol: 6,
              text: "    fn main() {",
            },
            { line: 99, col: 0, endLine: 99, endCol: 2, text: "fn helper()" },
          ],
        },
        {
          path: "target/debug/build.rs",
          ignored: true,
          matches: [{ line: 0, col: 0, endLine: 0, endCol: 2, text: "" }],
        },
      ],
    });
  });

  it("carries a regex compile error in detail with no files", () => {
    const parsed = parseFsGrepResult(
      buildGrepResult(8, FS_DONE_INVALID, 0, "unclosed character class", []),
    )!;
    expect(parsed.status).toBe(FS_DONE_INVALID);
    expect(parsed.detail).toBe("unclosed character class");
    expect(parsed.files).toEqual([]);
  });

  it("skips unknown record kinds via record_len", () => {
    const records = [
      ...fileRecord(0, 0, "a"),
      ...grepRecord(0x7f, strBytes("whatever")),
      ...fileRecord(0, 0, "b"),
    ];
    const got = [...fsGrepRecords(new Uint8Array(records))];
    expect(got.map((r) => (r.kind === "file" ? r.path : "?"))).toEqual([
      "a",
      "b",
    ]);
  });

  it("rejects a malformed frame rather than half-decoding it", () => {
    const good = buildGrepResult(1, FS_DONE_OK, 0, "", fileRecord(0, 0, "a"));
    expect(parseFsGrepResult(good.subarray(0, 5))).toBeNull();
    const wrongOpcode = good.slice();
    wrongOpcode[0] = 0x40;
    expect(parseFsGrepResult(wrongOpcode)).toBeNull();
    // A record claiming more body than the payload holds ends iteration.
    const overrun = new Uint8Array([...u32le(0xffff), FS_GREP_RECORD_FILE, 0]);
    expect([...fsGrepRecords(overrun)]).toEqual([]);
  });
});

